"""Built-in public-domain melodies used as a self-contained song corpus.

Each melody is a list of ``(midi_note, beats)`` pairs.  ``midi_note`` is a
standard MIDI pitch number (60 = middle C); ``beats`` is the note's duration in
beats.  A MIDI note of ``0`` denotes a rest.

These give the benchmark a guaranteed-available, license-clean corpus so the
end-to-end pipeline can be evaluated with zero external downloads.  The same
loader (``benchmark.corpus``) can additionally ingest a directory of real
``.mid`` files to scale the database to thousands of songs.
"""

# Note name -> MIDI helper for readability when transcribing tunes.
_C4 = 60
_N = {
	"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5,
	"F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11,
}


def n(name: str, octave: int) -> int:
	"""Note name + octave -> MIDI number, e.g. n('A', 4) == 69."""
	return (octave + 1) * 12 + _N[name]


def _seq(notes: list[tuple[str, int, float]]) -> list[tuple[int, float]]:
	return [(n(name, octv), beats) for name, octv, beats in notes]


